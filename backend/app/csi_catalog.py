def _item(digits: str, title: str) -> dict[str, str]:
    division = digits[:2]
    return {
        "digits": digits,
        "code": format_csi_display(digits) or digits,
        "title": title,
        "division": division,
        "division_name": DIVISION_NAMES.get(division, f"Division {division}"),
    }


def _merged_titles() -> dict[str, str]:
    out: dict[str, str] = {}
    for raw, title in (*_SECTIONS, *EXTRA_SECTIONS):
        digits = digits_from_csi(raw)
        if not digits or not (title or "").strip():
            continue
        out.setdefault(digits, title.strip())
    return out


_TITLES: dict[str, str] = _merged_titles()
_BY_DIGITS: dict[str, dict[str, str]] = {d: _item(d, t) for d, t in _TITLES.items()}
_ITEMS: list[dict[str, str]] = [_BY_DIGITS[d] for d in sorted(_TITLES)]


def catalog_size() -> int:
    return len(_ITEMS)


def title_for_code(raw: str | None) -> str | None:
    digits = digits_from_csi(raw)
    if not digits:
        return None
    item = _BY_DIGITS.get(digits)
    return item["title"] if item else None


def get_section(raw: str | None) -> dict[str, str] | None:
    digits = digits_from_csi(raw)
    if not digits:
        return None
    return _BY_DIGITS.get(digits)


def list_catalog(q: str | None = None, limit: int = 3000) -> list[dict[str, str]]:
    cap = max(1, min(int(limit or 3000), 5000))
    qq = (q or "").strip().lower()
    if not qq:
        return _ITEMS[:cap]
    q_digits = "".join(ch for ch in qq if ch.isdigit())
    out: list[dict[str, str]] = []
    for item in _ITEMS:
        blob = f"{item['code']} {item['title']} {item['division_name']}".lower()
        if qq in blob or (q_digits and q_digits in item["digits"]):
            out.append(item)
            if len(out) >= cap:
                break
    return out


def public_catalog(q: str | None = None, limit: int = 3000) -> dict[str, Any]:
    items = list_catalog(q, limit)
    return {"items": items, "total": catalog_size(), "entity": "csi_sections"}
